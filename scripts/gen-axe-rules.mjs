// Writes wcag/axe_rules.gen.go: every rule of the vendored axe-core
// (checks/a11y/vendor/axe.min.js) with the WCAG criteria, EN 301 549
// clauses and tags it carries and whether it is reviewOnFail, plus the
// SHA-256 of the file. A Go test
// fails when the vendored file's hash differs, so the table can't drift
// from the engine after an axe bump.
//
//   node scripts/gen-axe-rules.mjs     (or go generate ./wcag)
//
// For developers only and offline: axe is loaded in a plain vm context
// with no DOM, which is enough for axe.getRules(). CI needs no node, as
// the output is committed.

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendor = join(root, 'checks/a11y/vendor/axe.min.js');
const out = join(root, 'wcag/axe_rules.gen.go');

const src = readFileSync(vendor);
const sha = createHash('sha256').update(src).digest('hex');

// axe exports itself through module.exports when there is no window
// with getComputedStyle. The timer stubs are never called by getRules.
const ctx = { module: { exports: {} }, setTimeout() {}, clearTimeout() {} };
ctx.window = ctx;
vm.createContext(ctx);
vm.runInContext(src.toString('utf8'), ctx, { filename: 'axe.min.js' });
const axe = ctx.module.exports;
if (typeof axe.getRules !== 'function') {
  throw new Error('axe.min.js did not load: no axe.getRules');
}

// wcag1412 is 1.4.12: one digit each for the principle and the
// guideline, the rest is the criterion. wcag2a and wcag21aa are levels.
const criterion = (tag) => {
  const m = /^wcag(\d)(\d)(\d+)$/.exec(tag);
  return m ? `${m[1]}.${m[2]}.${m[3]}` : null;
};
const clause = (tag) => (/^EN-9\.[0-9.]+$/.test(tag) ? tag.slice(3) : null);
const byNumber = (a, b) => {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < Math.min(pa.length, pb.length); i++) {
    if (pa[i] !== pb[i]) return pa[i] - pb[i];
  }
  return pa.length - pb.length;
};
const list = (xs) => `[]string{${xs.map((x) => JSON.stringify(x)).join(', ')}}`;

// A reviewOnFail rule turns every failed check into an incomplete
// result, so it never reports a violation. getRules doesn't say which
// rules are; the loaded audit does.
if (!axe._audit || !Array.isArray(axe._audit.rules)) {
  throw new Error('axe.min.js did not load its rules: no axe._audit.rules');
}
const reviewOnFail = new Set(axe._audit.rules.filter((r) => r.reviewOnFail).map((r) => r.id));

const rules = axe.getRules().slice().sort((a, b) => (a.ruleId < b.ruleId ? -1 : 1));
const lines = rules.map((r) => {
  const tags = [...r.tags];
  const wcag = [...new Set(tags.map(criterion).filter(Boolean))].sort(byNumber);
  const en = [...new Set(tags.map(clause).filter(Boolean))].sort(byNumber);
  const fields = [];
  if (wcag.length) fields.push(`WCAG: ${list(wcag)}`);
  if (en.length) fields.push(`EN: ${list(en)}`);
  fields.push(`Tags: ${list(tags)}`);
  if (tags.includes('experimental')) fields.push('Experimental: true');
  if (reviewOnFail.has(r.ruleId)) fields.push('ReviewOnFail: true');
  return `\t${JSON.stringify(r.ruleId)}: {${fields.join(', ')}},`;
});

const go = `// Copyright (c) 2026 Rhythm Shahriar <me@rhy.io>
// SPDX-License-Identifier: MIT

// Code generated by scripts/gen-axe-rules.mjs; DO NOT EDIT.

package wcag

// AxeVersion is the version of the vendored axe-core the table was made
// from.
const AxeVersion = ${JSON.stringify(axe.version)}

// AxeSHA256 is the SHA-256 of checks/a11y/vendor/axe.min.js the table
// was made from.
const AxeSHA256 = ${JSON.stringify(sha)}

// AxeRules is every rule of the vendored axe-core by id, with the WCAG
// criteria and EN 301 549 clauses its tags name and whether it is
// reviewOnFail.
var AxeRules = map[string]Rule{
${lines.join('\n')}
}
`;
writeFileSync(out, go);

// gofmt aligns the table; without Go installed the file is still valid.
for (const gofmt of ['gofmt', '/usr/local/go/bin/gofmt']) {
  try {
    execFileSync(gofmt, ['-w', out]);
    break;
  } catch {
    // try the next one
  }
}
console.log(`wrote ${out}: ${rules.length} rules from axe ${axe.version}`);
