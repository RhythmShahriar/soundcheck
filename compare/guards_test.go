// capped is a page with the first n elements (of total) failing rule
// kept, as the a11y module keeps them, from element first on.
func capped(rule string, first, n, total int) model.Page {
	p := model.Page{Path: "/a11y/backlog.php", Audits: ok()}
	for i := first; i < first+n; i++ {
		p.Issues = append(p.Issues, a11yIssue(rule, fmt.Sprintf("li:nth-of-type(%d) > a", i)))
	}
	if total > n {
		p.Audits["a11y"] = model.Audit{Status: model.AuditOK, CappedRules: map[string]int{rule: total}}
	}
	return p
}

// Fixing one of the first 20 of 300 contrast problems frees a place in
// the 20 kept: element 21 shows up, which isn't NEW. The fixed one is
// FIXED (s83).
func TestCapGuardOneFixed(t *testing.T) {
	opts := model.Options{Modules: []string{"a11y"}, A11y: rules21()}
	beforePage := capped("color-contrast", 1, 20, 300)
	afterPage := capped("color-contrast", 1, 21, 299)
	afterPage.Issues = slices.Delete(afterPage.Issues, 4, 5) // element 5 fixed; 20 kept
	before := &model.Run{Options: opts, Pages: []model.Page{beforePage}}
	after := &model.Run{Options: opts, Pages: []model.Page{afterPage}}
	c := both(t, before, after)
	if got, want := changeLines(c.Changes), []string{"fixed a11y/color-contrast li:nth-of-type(5) > a /a11y/backlog.php "}; !slices.Equal(got, want) {
		t.Errorf("changes = %q, want %q", got, want)
	}
	if got, want := changeLines(c.Ignored), []string{"new a11y/color-contrast li:nth-of-type(21) > a /a11y/backlog.php beyond the elements kept per rule"}; !slices.Equal(got, want) {
		t.Errorf("ignored = %q, want %q", got, want)
	}
}

// Five problems added before the kept ones push five of them past the
// cap: they aren't FIXED. The five added are NEW: the snapshot wasn't
// capped, so it saw every element.
func TestCapGuardPushedPastTheCap(t *testing.T) {
	opts := model.Options{Modules: []string{"a11y"}, A11y: rules21()}
	beforePage := capped("color-contrast", 6, 20, 20)
	afterPage := capped("color-contrast", 1, 20, 25)
	before := &model.Run{Options: opts, Pages: []model.Page{beforePage}}
	after := &model.Run{Options: opts, Pages: []model.Page{afterPage}}
	c := both(t, before, after)
	var newN, ignoredFixed int
	for _, ch := range c.Changes {
		if ch.Class != model.New {
			t.Errorf("change %q", changeLines([]model.Change{ch}))
		}
		newN++
	}
	for _, ch := range c.Ignored {
		if ch.Class == model.Fixed && ch.Reason == "beyond the elements kept per rule" {
			ignoredFixed++
		}
	}
	if newN != 5 || ignoredFixed != 5 || len(c.Ignored) != 5 {
		t.Errorf("new %d, ignored fixed %d: changes %q ignored %q", newN, ignoredFixed, changeLines(c.Changes), changeLines(c.Ignored))
	}
}

// A rule capped on another page, or another rule capped on this page,
// doesn't guard: a NEW there is NEW.
func TestCapGuardOnlyThatRuleAndPage(t *testing.T) {
	opts := model.Options{Modules: []string{"a11y"}, A11y: rules21()}
	beforeBacklog := capped("color-contrast", 1, 20, 300)
	before := &model.Run{Options: opts, Pages: []model.Page{beforeBacklog, {Path: "/", Audits: ok()}}}
	afterBacklog := capped("color-contrast", 1, 20, 300)
	afterBacklog.Issues = append(afterBacklog.Issues, a11yIssue("label", "#q"))
	after := &model.Run{Options: opts, Pages: []model.Page{afterBacklog, {Path: "/", Audits: ok(), Issues: []model.Issue{a11yIssue("color-contrast", "h1")}}}}
	c := both(t, before, after)
	want := []string{"new a11y/color-contrast h1 / ", "new a11y/label #q /a11y/backlog.php "}
	if got := changeLines(c.Changes); !slices.Equal(got, want) {
		t.Errorf("changes = %q, want %q", got, want)
	}
	if len(c.Ignored) != 0 {
		t.Errorf("ignored = %q", changeLines(c.Ignored))
	}
}

// legacyPage is a 1.2 snapshot's page: the first 20 elements of total
// failing rule, each with the detail 1.2 gave a capped rule (none when
// total is 20 or less). 1.2 didn't record CappedRules.
func legacyPage(rule string, total int) model.Page {
	p := capped(rule, 1, min(total, 20), 0)
	p.Audits = nil
	for i := range p.Issues {
		if total > 20 {
			p.Issues[i].Detail = fmt.Sprintf("Contrast too low.\nThe first 20 of %d elements that fail this rule on the page are reported.", total)
		}
	}
	return p
}

// A 1.2 snapshot capped rules at 20 without saying so. A 1.3 run that
// keeps 50 per rule sees elements 21 to 50, which were there all along:
// not NEW. The detail says the rule was capped; so does a rule that
// kept exactly 20. Under 20 it wasn't capped and a NEW is NEW.
func TestCapGuardLegacySnapshot(t *testing.T) {
	legacy := func(p model.Page) *model.Run {
		return &model.Run{Options: model.Options{Modules: []string{"a11y"}}, Pages: []model.Page{p}}
	}
	opts := model.Options{Modules: []string{"a11y"}, A11y: rules21()}
	opts.A11y.MaxElements = 50
	for _, c := range []struct {
		name          string
		before        model.Page
		after         model.Page
		changes, kept int
	}{
		{"detail says 300", legacyPage("color-contrast", 300), capped("color-contrast", 1, 50, 300), 0, 30},
		{"exactly 20 kept", legacyPage("color-contrast", 20), capped("color-contrast", 1, 25, 25), 0, 5},
		{"19 kept", legacyPage("color-contrast", 19), capped("color-contrast", 1, 25, 25), 6, 0},
	} {
		t.Run(c.name, func(t *testing.T) {
			cmp := both(t, legacy(c.before), &model.Run{Options: opts, Pages: []model.Page{c.after}})
			if len(cmp.Changes) != c.changes || len(cmp.Ignored) != c.kept {
				t.Errorf("changes %q ignored %q", changeLines(cmp.Changes), changeLines(cmp.Ignored))
			}
			for _, ch := range cmp.Ignored {
				if ch.Reason != reasonBeyondCap {
					t.Errorf("ignored %q", changeLines([]model.Change{ch}))
				}
			}
		})
	}
}

// Soundcheck before 1.3 dropped the violations of <html> and <body>
// themselves. A missing lang the 1.2 snapshot never reported isn't NEW;
// against a 1.3 snapshot, which reports them, it is.
func TestDocumentElementAgainstOldSnapshot(t *testing.T) {
	before := loadRun(t, "run-1.2.json")
	lang := a11yIssue("html-has-lang", "html")
	label := a11yIssue("label", "#email")
	after := &model.Run{Options: model.Options{Modules: []string{"health", "a11y"}, WCAG: "2.1", A11y: rules21()}, Pages: []model.Page{
		{Path: "/checkout/", Status: 200, Issues: append(slices.Clone(before.Pages[0].Issues), lang, label), Audits: ok()},
	}}
	c := both(t, before, after)
	if got, want := changeLines(c.Changes), []string{"new a11y/label #email /checkout/ "}; !slices.Equal(got, want) {
		t.Errorf("changes = %q, want %q", got, want)
	}
	if got, want := changeLines(c.Ignored), []string{"new a11y/html-has-lang html /checkout/ the baseline didn't report the page's <html> or <body>"}; !slices.Equal(got, want) {
		t.Errorf("ignored = %q, want %q", got, want)
	}

	snap := &model.Run{Options: after.Options, Pages: []model.Page{{Path: "/checkout/", Status: 200, Audits: ok()}}}
	snap.Options.A11y = rules21()
	c = both(t, snap, after)
	if !slices.Contains(changeLines(c.Changes), "new a11y/html-has-lang html /checkout/ ") {
		t.Errorf("against a 1.3 snapshot: changes = %q", changeLines(c.Changes))
	}
}
