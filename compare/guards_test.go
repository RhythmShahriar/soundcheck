var update = flag.Bool("update", false, "rewrite baseline_rules.go from the a11y module's 2.0 golden")

// baselineRules is generated from the a11y module's golden of the 2.0
// rules, so a 1.2 snapshot is judged by the rules it really ran.
func TestBaselineRules(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "checks", "a11y", "testdata", "rules-2.0.golden"))
	if err != nil {
		t.Fatal(err)
	}
	want := strings.Fields(string(data))
	if *update {
		var b strings.Builder
		b.WriteString("// Copyright (c) 2026 Rhythm Shahriar <me@rhy.io>\n// SPDX-License-Identifier: MIT\n\n")
		b.WriteString("// Code generated by go test -run TestBaselineRules -update; DO NOT EDIT.\n\npackage compare\n\n")
		b.WriteString("// baselineRules are the axe-core rules a run made before 1.3 applied:\n")
		b.WriteString("// the WCAG 2.0 A and AA rules of axe-core 4.14.0, from\n// checks/a11y/testdata/rules-2.0.golden.\n")
		b.WriteString("var baselineRules = []string{\n")
		for _, r := range want {
			fmt.Fprintf(&b, "\t%q,\n", r)
		}
		b.WriteString("}\n")
		if err := os.WriteFile("baseline_rules.go", []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if !slices.Equal(baselineRules, want) {
		t.Errorf("baseline_rules.go differs from the 2.0 golden; go test -run TestBaselineRules -update rewrites it")
	}
	for _, r := range []string{"autocomplete-valid", "avoid-inline-spacing", "label-content-name-mismatch", "target-size"} {
		if slices.Contains(baselineRules, r) {
			t.Errorf("%s isn't a 2.0 rule", r)
		}
	}
}

// loadRun reads a stored run from testdata, keyed as a stored run is.
func loadRun(t *testing.T, name string) *model.Run {
	t.Helper()
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatal(err)
	}
	var r model.Run
	if err := json.Unmarshal(data, &r); err != nil {
		t.Fatal(err)
	}
	for i := range r.Pages {
		for j := range r.Pages[i].Issues {
			r.Pages[i].Issues[j].Identify()
		}
	}
	return &r
}

func rules21() *model.A11yRules {
	rules := append(slices.Clone(baselineRules), "autocomplete-valid", "avoid-inline-spacing", "label-content-name-mismatch")
	slices.Sort(rules)
	return &model.A11yRules{Axe: "4.14.0", Rules: rules, MaxElements: 20}
}

func changeLines(cs []model.Change) []string {
	var out []string
	for _, c := range cs {
		out = append(out, c.Class+" "+c.Check+" "+c.Source+" "+strings.Join(c.Pages, ",")+" "+c.Reason)
	}
	return out
}

// A snapshot made by 1.2 ran the 2.0 rules only. A 1.3 run with the 2.1
// rules finds an autocomplete problem that was always there: it isn't
// NEW (product.md s60).
func TestRuleNotInBaseline(t *testing.T) {
	before := loadRun(t, "run-1.2.json")
	if before.Options.A11y != nil {
		t.Fatal("the 1.2 fixture records rules")
	}
	auto := a11yIssue("autocomplete-valid", "#card-number")
	contrast := a11yIssue("color-contrast", "footer a")
	contrast.Title = before.Pages[0].Issues[0].Title
	contrast.Identify()
	after := &model.Run{Options: model.Options{Modules: []string{"health", "a11y"}, WCAG: "2.1", A11y: rules21()}, Pages: []model.Page{
		{Path: "/checkout/", Status: 200, Issues: []model.Issue{contrast, auto}, Audits: ok()},
	}}
	c := both(t, before, after)
	if len(c.Changes) != 0 {
		t.Errorf("changes = %q", changeLines(c.Changes))
	}
	if got, want := changeLines(c.Ignored), []string{"new a11y/autocomplete-valid #card-number /checkout/ rule not in the baseline"}; !slices.Equal(got, want) {
		t.Errorf("ignored = %q, want %q", got, want)
	}
	w := "note: 3 rules didn't run in the baseline (autocomplete-valid, avoid-inline-spacing, label-content-name-mismatch); their issues aren't counted as new. Take a new snapshot to include them"
	if !slices.Contains(c.Warnings, w) {
		t.Errorf("warnings = %q", c.Warnings)
	}
	if c.Summary.New != 0 || c.Summary.Ignored != 1 {
		t.Errorf("summary = %+v", c.Summary)
	}
}

// A rule an axe-core upgrade added isn't in the snapshot's recorded
// rules: its issues aren't NEW either. A rule both ran still gives NEW.
func TestRuleAddedByAxeUpgrade(t *testing.T) {
	opts := func(rules ...string) model.Options {
		return model.Options{Modules: []string{"a11y"}, WCAG: "2.1", A11y: &model.A11yRules{Axe: "4.14.0", Rules: rules}}
	}
	before := &model.Run{Options: opts("color-contrast", "label"), Pages: []model.Page{{Path: "/", Audits: ok()}}}
	after := &model.Run{Options: opts("color-contrast", "label", "x-new-rule"), Pages: []model.Page{
		{Path: "/", Audits: ok(), Issues: []model.Issue{a11yIssue("x-new-rule", "main"), a11yIssue("label", "#email")}},
	}}
	c := both(t, before, after)
	if got, want := changeLines(c.Changes), []string{"new a11y/label #email / "}; !slices.Equal(got, want) {
		t.Errorf("changes = %q, want %q", got, want)
	}
	if got, want := changeLines(c.Ignored), []string{"new a11y/x-new-rule main / rule not in the baseline"}; !slices.Equal(got, want) {
		t.Errorf("ignored = %q, want %q", got, want)
	}
	w := "note: 1 rule didn't run in the baseline (x-new-rule); their issues aren't counted as new. Take a new snapshot to include them"
	if !slices.Contains(c.Warnings, w) {
		t.Errorf("warnings = %q", c.Warnings)
	}
}

// Runs with the same rules get no note. A module that isn't a11y
// is never guarded.
func TestSameRulesNoNote(t *testing.T) {
	opts := model.Options{Modules: []string{"a11y", "health"}, A11y: rules21()}
	php := issue("health/php-error", model.Warning, "PHP Warning")
	before := &model.Run{Options: opts, Pages: []model.Page{{Path: "/", Audits: ok()}}}
	after := &model.Run{Options: opts, Pages: []model.Page{{Path: "/", Audits: ok(), Issues: []model.Issue{php, a11yIssue("autocomplete-valid", "#cc")}}}}
	c := both(t, before, after)
	if len(c.Changes) != 2 || len(c.Ignored) != 0 {
		t.Errorf("changes = %q, ignored = %q", changeLines(c.Changes), changeLines(c.Ignored))
	}
	for _, w := range c.Warnings {
		if strings.Contains(w, "baseline") {
			t.Errorf("warning %q", w)
		}
	}
}

// A 2.2 snapshot compared with a 2.1 run: target-size didn't run in the
