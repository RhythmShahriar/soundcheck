// scoreboard renders docs/benchmark.md.
func scoreboard(m *Manifest, outcomes []Outcome, rounds []ControlRound, version string, binErr error, tools []*Tool, partial bool) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	ran := map[string]bool{}
	for _, t := range tools {
		ran[t.Key] = true
	}

	sc := score(outcomes)
	w("<!-- Generated by `go run -tags testbed ./testbed/bench`. Don't edit by hand: rerun the benchmark. -->\n\n")
	w("# Soundcheck benchmark\n\n")
	w("The testbed (`testbed/`) is a WordPress site and a plain-PHP site with %d scenarios. Each scenario has a good state and a broken state, ", len(m.Scenarios))
	w("switched by `testbed/toggle.sh`. For every scenario the benchmark sets the good state, runs `rhythm-soundcheck snapshot`, breaks the scenario, ")
	w("runs `rhythm-soundcheck compare` and checks the comparison for the change listed in `testbed/scenarios.yaml`. ")
	w("A control pass then breaks nothing: it takes a snapshot and compares twice. Every change at or above NEW counts as a false alarm.\n\n")
	switch {
	case binErr != nil:
		w("**Soundcheck wasn't run:** %s.\n\n", binErr)
	default:
		w("**Soundcheck caught %d of %d scenarios.**", sc.caught, sc.total)
		if len(rounds) > 0 {
			w(" **False alarms: %d** in %d compares of an unchanged site.", falseAlarmCount(rounds), 2*len(rounds))
		} else {
			w(" The control pass wasn't run (`-control 0`, or a partial run).")
		}
		if partial {
			w(" (a partial run: `-only` was used)")
		}
		w("\n\n")
		if sc.pending > 0 {
			w("%d more scenarios wait for detectors that aren't merged yet; they are listed apart under [Pending](#pending) and not counted (%d of them caught already).\n\n",
				sc.pending, sc.pendingCaught)
		}
	}
	ver := version
	if ver == "" {
		ver = "unknown version"
	}
	w("Run on %s with %s (%s/%s).\n\n", time.Now().UTC().Format("2006-01-02"), ver, runtime.GOOS, runtime.GOARCH)

	var counted, pending []Outcome
	for _, o := range outcomes {
		if o.Scenario.Pending {
			pending = append(pending, o)
		} else {
			counted = append(counted, o)
		}
	}
	table(&b, counted, ran)
	w("\n**caught**: the expected result was reported · found, as X: the problem was reported in another class · false alarm: a change the scenario rules out was reported · missed · error: the tool failed (see Details) · not run: the tool wasn't available\n\n")

	if len(pending) > 0 {
		w("## Pending\n\n")
		w("These scenarios expect a detector or fix that another part of the roadmap is building. They run like the others but don't count in the score. ")
		w("When one shows **caught**, its `pending: true` can go from `testbed/scenarios.yaml`.\n\n")
		table(&b, pending, ran)
		w("\n")
		for _, o := range pending {
			if o.Scenario.Note != "" {
				w("- **%s**: %s\n", o.Scenario.ID, o.Scenario.Note)
			}
		}
		w("\n")
	}

	if len(rounds) > 0 {
		controlSection(&b, m, rounds)
	}

	w("## Details\n\n")
	for _, o := range outcomes {
		s := o.Scenario
		w("**%s %s** (`%s` on %s). Broken state: %s.\n", s.ID, s.Name, s.Path, s.Site, s.Toggle)
		r := o.Soundcheck
		switch {
		case r.Outcome == FalseAlarm:
			w("Soundcheck: false alarm, %s.", r.Found)
		case r.Found != "":
			w("Soundcheck: %s.", r.Found)
		case r.Detail != "":
			w("Soundcheck: %s.", r.Detail)
		default:
			w("Soundcheck: %s.", r.Outcome)
		}
		if len(r.Others) > 0 {
			w(" Also reported: %s.", strings.Join(r.Others, "; "))
		}
		w("\n")
		for _, t := range allTools {
			if tr, ok := o.Tools[t.Key]; ok && (tr.Found != "" || tr.Detail != "") {
				w("%s: %s.\n", t.Name, strings.TrimSuffix(tr.Found+tr.Detail, "."))
			}
		}
		w("\n")
	}

	w("## Tools\n\n")
	for _, t := range allTools {
		state := "ran"
		if !ran[t.Key] {
			state = "not run; to include it, " + t.HowTo
		}
		w("- **%s**: %s. %s.\n", t.Name, t.About, upper(state))
	}
	w("\nA tool is only expected to catch what it's built for (a link checker won't see a JS error); the table shows where each one helps.\n\n")

	w("## Run it\n\n")
	w("```sh\nmake build                 # bin/rhythm-soundcheck\nmake -C testbed up         # WordPress on :18800, plain PHP on :18810 (about 30 s)\n")
	w("go run -tags testbed ./testbed/bench                      # Soundcheck + installed tools\n")
	w("go run -tags testbed ./testbed/bench -tools all           # also fetch BackstopJS, lychee and Unlighthouse\n")
	w("go run -tags testbed ./testbed/bench -only s05,s09        # some scenarios (no control pass unless -control is given)\n")
	w("go run -tags testbed ./testbed/bench -control 0           # skip the control pass\nmake -C testbed down\n```\n\n")
	w("Scenarios that need a login (%s) use the testbed's own account unless `SOUNDCHECK_USER` and `SOUNDCHECK_PASSWORD` are set.\n",
		strings.Join(loginScenarios(m), ", "))
	w("Scenarios that need Echo (%s) run only with `-echo http://127.0.0.1:8025` and Echo running.\n", strings.Join(echoScenarios(m), ", "))
	w("Runs are kept in `testbed/bench/work/<id>/` (snapshot, compare.json, tool output) and the control pass in `work/control/`; `work/results.json` has every result.\n")
	return b.String()
}

// table writes the scoreboard table for some outcomes.
func table(b *strings.Builder, outcomes []Outcome, ran map[string]bool) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	w("| # | Scenario | Expected | Soundcheck |")
	for _, t := range allTools {
		w(" %s |", t.Name)
	}
	w("\n|---|---|---|---|")
	for range allTools {
		w("---|")
	}
	w("\n")
	for _, o := range outcomes {
		s := o.Scenario
		var exp []string
		for _, e := range s.Expect {
			exp = append(exp, cell(e.String()))
		}
		expected := strings.Join(exp, "<br>or ") + " (" + s.Module + ")"
		if len(s.Forbid) > 0 {
			var no []string
			for _, f := range s.Forbid {
				no = append(no, cell(f.String()))
			}
			expected += "<br>and no " + strings.Join(no, ", ")
		}
		w("| %s | %s | %s | %s |", s.ID, cell(s.Name), expected, cell(mark(o.Soundcheck)))
		for _, t := range allTools {
			r, ok := o.Tools[t.Key]
			switch {
			case !ran[t.Key]:
				w(" not run |")
			case !ok:
				w(" – |")
			default:
				w(" %s |", cell(mark(r)))
			}
		}
		w("\n")
	}
}

// controlSection writes the control pass: false alarms per site and the
// changes behind them.
func controlSection(b *strings.Builder, m *Manifest, rounds []ControlRound) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	w("## Control pass\n\n")
	w("Every scenario good. Each round takes a snapshot of the site (at most %d pages) and compares twice with nothing changed. ", m.Control.Limit)
	w("A change at or above NEW in either compare is a false alarm.\n\n")
	w("| Site | Rounds | Compares | Pages | False alarms | Errors |\n|---|---:|---:|---:|---:|---:|\n")
	seen := map[string]int{}
	var order []string
	for _, site := range m.Control.Sites {
		var n, pages, alarms, errs int
		for _, r := range rounds {
			if r.Site != site {
				continue
			}
			n++
			pages = max(pages, r.Pages)
			alarms += len(r.Alarms)
			if r.Error != "" {
				errs++
			}
			for _, a := range r.Alarms {
				if seen[a] == 0 {
					order = append(order, a)
				}
				seen[a]++
			}
		}
		if n > 0 {
			w("| %s | %d | %d | %d | %d | %d |\n", site, n, 2*(n-errs), pages, alarms, errs)
		}
	}
	w("\n")
	if len(order) > 0 {
		w("False alarms, with how often each was reported:\n\n")
		for _, a := range order {
			w("- %s (%d×)\n", cell(a), seen[a])
		}
		w("\n")
	}
	for _, r := range rounds {
		if r.Error != "" {
			w("- %s round %d didn't finish: %s\n", r.Site, r.Round, cell(r.Error))
		}
	}
	w("\n")
}

func mark(r Result) string {
	switch r.Outcome {
	case Caught:
		return "**caught**"
	case OtherClass:
		cls, _, _ := strings.Cut(r.Found, " ")
		return "found, as " + strings.ToUpper(cls)
	case Missed:
		return "missed"
	case FalseAlarm:
		return "false alarm"
	case Failed:
		return "error"
	}
	return r.Outcome
}

func loginScenarios(m *Manifest) []string {
	var ids []string
	for _, s := range m.Scenarios {
		if s.Login {
			ids = append(ids, s.ID)
		}
	}
	return slices.Clip(ids)
}

func echoScenarios(m *Manifest) []string {
	var ids []string
	for _, s := range m.Scenarios {
		if s.Echo {
			ids = append(ids, s.ID)
		}
	}
	return ids
}

// cell escapes text for a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}

func upper(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
